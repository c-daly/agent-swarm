class TelemetryCollector:
    """Real-time telemetry collection for MCP router using v2 schema.

    Tracks all tool calls, durations, token estimates, and errors.
    Writes to telemetry.json on every event for real-time dashboard updates.
    Uses the unified v2 telemetry schema.
    """

    # Token estimates by tool type (conservative estimates)
    TOKEN_ESTIMATES = {
        "read_file": 2000,
        "find_symbol": 1500,
        "search_for_pattern": 1500,
        "get_symbols_overview": 1000,
        "list_dir": 500,
        "find_file": 500,
        "replace_content": 800,
        "replace_symbol_body": 1000,
        "insert_after_symbol": 800,
        "insert_before_symbol": 800,
        "execute_shell_command": 1000,
    }

    # Subagent token estimates (much larger)
    SUBAGENT_TOKEN_ESTIMATES = {
        "Explore": 25000,
        "Plan": 30000,
        "Implement": 100000,
        "general-purpose": 50000,
        "Bash": 10000,
        "feature-dev:code-explorer": 40000,
        "feature-dev:code-reviewer": 30000,
        "feature-dev:code-architect": 50000,
    }

    def __init__(
        self,
        telemetry_file: Optional[Path] = None,
        max_events: int = 500,
        telemetry_service: Optional['TelemetryService'] = None
    ):
        """Initialize telemetry collector.

        Args:
            telemetry_file: Path to write telemetry JSON
            max_events: Maximum events to keep (rolling window)
            telemetry_service: Optional TelemetryService for DuckDB persistence
        """
        self._telemetry_file = telemetry_file or Path.home() / ".claude/plugins/agent-swarm/.state/telemetry.json"
        self._max_events = max_events
        self._telemetry_service = telemetry_service
        self._lock = Lock()
        self._pending_requests: dict[str, tuple[str, str, dict, float]] = {}
        self._session_id = datetime.now(timezone.utc).isoformat()
        self._events: list[dict] = []  # Session events (rolling window)
        self._data: TelemetryV2 = load_telemetry_v2(self._telemetry_file)

    def _save(self) -> None:
        """Save telemetry to file using v2 schema."""
        save_telemetry_v2(self._data, self._telemetry_file)

    def _estimate_tokens(self, tool: str, subagent_type: str = "") -> int:
        """Estimate tokens for a tool call."""
        if subagent_type:
            return self.SUBAGENT_TOKEN_ESTIMATES.get(subagent_type, 50000)
        base_tool = tool.split("__")[-1] if "__" in tool else tool
        return self.TOKEN_ESTIMATES.get(base_tool, 500)

    def _get_today_key(self) -> str:
        """Get today's date key in YYYY-MM-DD format."""
        return datetime.now(timezone.utc).strftime("%Y-%m-%d")

    def track_request(self, destination: str, tool_name: str, args: dict) -> str:
        """Called when a request is made. Returns correlation_id."""
        import time
        correlation_id = f"req-{int(time.time() * 1000)}-{hash((destination, tool_name)) & 0xFFFF:04x}"

        with self._lock:
            self._pending_requests[correlation_id] = (
                tool_name, destination, args, time.time()
            )
        return correlation_id

    def track_response(
        self,
        correlation_id: str,
        error: bool = False,
        error_msg: str = "",
        full_size: int = 0,
        summary_size: int = 0
    ) -> None:
        """Called when a response is received.

        Args:
            correlation_id: Request correlation ID
            error: Whether the request errored
            error_msg: Error message if any
            full_size: Size of full response in chars (for efficiency tracking)
            summary_size: Size of summary in chars (for efficiency tracking)
        """
        import time

        with self._lock:
            if correlation_id not in self._pending_requests:
                return

            tool_name, backend, args, start_time = self._pending_requests.pop(correlation_id)
            duration_ms = int((time.time() - start_time) * 1000)

            # Check for subagent
            subagent_type = args.get("subagent_type", "") if tool_name == "Task" else ""
            tokens_est = self._estimate_tokens(tool_name, subagent_type)

            # Create event for session tracking
            event = {
                "ts": datetime.now(timezone.utc).isoformat(),
                "tool": tool_name,
                "backend": backend,
                "duration_ms": duration_ms,
                "status": "error" if error else "success",
                "tokens_est": tokens_est,
                "subagent_type": subagent_type,
                "error_msg": error_msg[:200] if error_msg else "",
                "full_size": full_size,
                "summary_size": summary_size
            }

            # Add to session events (rolling window)
            self._events.append(event)
            if len(self._events) > self._max_events:
                self._events = self._events[-self._max_events:]

            # Update v2 telemetry
            self._update_v2_telemetry(event, error, full_size, summary_size, duration_ms)

            # Send to TelemetryService if available (dual-write during migration)
            if self._telemetry_service:
                self._send_to_service(event, error_msg)

            # Save immediately for real-time updates
            self._save()

    def _update_v2_telemetry(
        self,
        event: dict,
        error: bool,
        full_size: int,
        summary_size: int,
        duration_ms: int
    ) -> None:
        """Update v2 telemetry structure."""
        day_key = self._get_today_key()
        day_data = ensure_day(self._data, day_key)

        # Update call counts
        calls = day_data.setdefault("calls", {"total": 0, "by_tool": {}, "by_backend": {}})
        calls["total"] = calls.get("total", 0) + 1

        tool = event["tool"]
        calls.setdefault("by_tool", {})[tool] = calls.get("by_tool", {}).get(tool, 0) + 1

        backend = event["backend"]
        calls.setdefault("by_backend", {})[backend] = calls.get("by_backend", {}).get(backend, 0) + 1

        # Update timing stats
        timing = day_data.setdefault("timing", {"avg_response_ms": 0.0, "p95_response_ms": 0.0, "by_backend": {}})
        update_timing_stats(timing, backend, duration_ms)

        # Update summarization stats if applicable
        if full_size > 0 and summary_size > 0:
            summ = day_data.setdefault("summarization", {
                "offered": 0, "accepted": 0, "rejected": 0,
                "acceptance_rate": 0.0, "tokens_saved_est": 0
            })
            summ["offered"] = summ.get("offered", 0) + 1
            summ["accepted"] = summ.get("accepted", 0) + 1  # Router always accepts
            chars_saved = full_size - summary_size
            tokens_saved = chars_saved // 4  # ~4 chars per token
            summ["tokens_saved_est"] = summ.get("tokens_saved_est", 0) + tokens_saved
            total = summ.get("offered", 1)
            summ["acceptance_rate"] = summ.get("accepted", 0) / total if total > 0 else 0.0

        # Track session
        sessions = day_data.setdefault("sessions", [])
        if self._session_id not in sessions:
            sessions.append(self._session_id)

    def _send_to_service(self, event: dict, error_msg: str) -> None:
        """Send event to TelemetryService for DuckDB persistence.
        
        Maps TelemetryCollector event format to TelemetryService expected format.
        
        Args:
            event: Event dict from track_response
            error_msg: Error message if error occurred
        """
        # Map TelemetryCollector fields to TelemetryService/DuckDB schema
        service_event = {
            "timestamp": event["ts"],  # ts -> timestamp
            "session_id": self._session_id,
            "tool": event["tool"],
            "backend": event["backend"],
            "duration_ms": event["duration_ms"],
            "status": event["status"],
        }
        
        # Add optional fields
        if event.get("subagent_type"):
            service_event["agent_type"] = event["subagent_type"]  # subagent_type -> agent_type
        
        # Add error type if error occurred
        if event["status"] == "error" and error_msg:
            # Extract error type from message (simple heuristic)
            service_event["error_type"] = error_msg.split(":")[0] if ":" in error_msg else "Error"
        
        # Add summarization fields if applicable
        if event.get("full_size", 0) > 0 and event.get("summary_size", 0) > 0:
            service_event["was_summarized"] = True
            service_event["original_size"] = event["full_size"]
            service_event["summary_size"] = event["summary_size"]
        
        # Send to service
        try:
            self._telemetry_service.insert_event(service_event)
        except Exception:
            # Don't let telemetry failures break routing
            pass

    def get_summary(self) -> dict:
        """Get current telemetry summary."""
        with self._lock:
            day_key = self._get_today_key()
            day_data = self._data.get("days", {}).get(day_key, {})

            calls = day_data.get("calls", {})
            timing = day_data.get("timing", {})
            summ = day_data.get("summarization", {})

            # Compute efficiency metrics from summarization data
            tokens_saved = summ.get("tokens_saved_est", 0)
            offered = summ.get("offered", 0)
            
            # Get socket events if tracked
            socket_events = getattr(self, '_socket_events', [])
            socket_summary = {}
            if socket_events:
                # Count by status
                by_status = {}
                total_duration = 0
                for evt in socket_events:
                    status = evt.get("status", "unknown")
                    by_status[status] = by_status.get(status, 0) + 1
                    total_duration += evt.get("duration_ms", 0)
                socket_summary = {
                    "total": len(socket_events),
                    "by_status": by_status,
                    "avg_duration_ms": total_duration // len(socket_events) if socket_events else 0,
                    "recent": socket_events[-5:]  # Last 5 socket events
                }

            return {
                "session_id": self._session_id,
                "event_count": len(self._events),
                "today": day_key,
                "aggregates": {
                    "by_tool": calls.get("by_tool", {}),
                    "by_backend": calls.get("by_backend", {}),
                    "totals": {"calls": calls.get("total", 0)},
                    "timing": timing,
                    "efficiency": {
                        "calls_summarized": offered,
                        "tokens_saved_est": tokens_saved,
                    }
                },
                "socket": socket_summary,
                "recent_events": self._events[-10:]  # Last 10
            }




class MCPRouter:
    """Thread-safe MCP request router with backpressure handling.

    Routes requests to registered target servers, summarizes responses,
    and returns {summary, full} envelope.

    Connections are spawned on first use and kept alive for reuse.
    Per-backend locks ensure safe concurrent access.

    Summarizer options:
        - "openai": Use OpenAI API (requires OPENAI_API_KEY)
        - "anthropic": Use Anthropic API (requires ANTHROPIC_API_KEY)
        - "none": Use fallback heuristics only

    Hook points:
        on_request: Called before forwarding (destination, tool, args)
        on_response: Called after response packaged (RouterResponse)
    """

    # Default models for each provider
    DEFAULT_MODELS = {
        "openai": "gpt-4o-mini",
        "anthropic": "claude-3-5-haiku-20241022",
    }

    def __init__(
        self,
        max_queue_size: int = 1000,
        summarizer: str = "auto",
        summarizer_model: Optional[str] = None,
        enable_telemetry: bool = True,
    ):
        """Initialize router with request queue and lock.

        Args:
            max_queue_size: Maximum pending requests before blocking.
            summarizer: Provider for summarization ("auto", "openai", "anthropic", "none").
                        "auto" tries openai first, then anthropic, then falls back.
            summarizer_model: Model to use (defaults based on provider).
            enable_telemetry: Enable real-time telemetry collection.
        """
        self._queue: deque = deque(maxlen=max_queue_size)
        self._lock = Lock()
        self._servers: dict[str, ServerConfig] = {}
        self._connections: dict[str, subprocess.Popen] = {}  # Live backend processes
        self._backend_locks: dict[str, RLock] = {}  # Per-backend locks

        # Shadow cache for workflow state (survives backend respawns)
        self._workflow_state_cache: dict[str, dict] = {}
        # Counter for generating unique content IDs
        self._content_id_counter = 0
        # Storage for content that can be retrieved by ID (for two-step content retrieval)
        self._content_store: dict[str, Any] = {}

        # Initialize summarizer (decide provider once at startup)
        self._llm_call: Callable[[str], str] = self._init_summarizer(summarizer, summarizer_model)

        # Hook points for extensibility (logging, telemetry, testing)
        self.on_request: list[Callable[[str, str, dict], None]] = []
        self.on_response: list[Callable[[RouterResponse], None]] = []

        # Event system for async tool execution
        self._event_queue: dict[str, list[dict]] = {}  # topic -> events
        self._event_responses: dict[str, dict] = {}  # correlation_id -> response
        self._event_lock = Lock()

        # Telemetry collector for real-time metrics
        self.telemetry: Optional[TelemetryCollector] = TelemetryCollector() if enable_telemetry else None

        # Socket listener for external clients (hooks, CLIs)
        self._socket_server: Optional[socket.socket] = None
        self._socket_thread: Optional[Thread] = None
        self._socket_port: int = 0
        self._socket_running: bool = False
        self._port_file = Path(__file__).parent.parent / ".state" / "router.port"

        # Federation state
        self._is_primary: bool = False  # True if we own the socket listener
        self._main_router_port: int = 0  # Port of main router (if we're secondary)

    def _cache_workflow_state(self, tool_name: str, args: dict, response: dict) -> None:
        """Cache workflow state from set/update/start operations."""
        if tool_name == "workflow_set_state":
            workflow_id = args.get("workflow_id")
            state = args.get("state")
            if workflow_id and state:
                self._workflow_state_cache[workflow_id] = state
        elif tool_name == "workflow_start":
            workflow_id = args.get("workflow_id")
            state = args.get("initial_state")
            if workflow_id and state:
                self._workflow_state_cache[workflow_id] = state
        elif tool_name == "workflow_stop":
            workflow_id = args.get("workflow_id")
            if workflow_id:
                self._workflow_state_cache.pop(workflow_id, None)

    def _restore_workflow_state(self, server_name: str) -> None:
        """Restore cached workflow state to a freshly spawned backend."""
        if server_name != "workflow" or not self._workflow_state_cache:
            return
        # Restore each cached workflow
        server = self._servers.get(server_name)
        if not server:
            return
        for workflow_id, state in self._workflow_state_cache.items():
            try:
                self._forward_to_server(server, "workflow_set_state", {
                    "workflow_id": workflow_id,
                    "state": state
                }, _is_restore=True)
            except Exception:
                pass  # Best effort  # Best effort

    def clear_workflow_cache(self, workflow_id: str | None = None) -> dict:
        """Clear cached workflow state.
        
        Args:
            workflow_id: Specific workflow to clear, or None for all.
            
        Returns:
            Dict with cleared workflow IDs.
        """
        if workflow_id:
            existed = self._workflow_state_cache.pop(workflow_id, None) is not None
            return {"cleared": [workflow_id] if existed else [], "all": False}
        else:
            cleared = list(self._workflow_state_cache.keys())
            self._workflow_state_cache.clear()
            return {"cleared": cleared, "all": True}

    def _init_summarizer(
        self,
        provider: str,
        model: Optional[str]
    ) -> Callable[[str], str]:
        """Initialize summarizer and return the LLM call function.

        Decides provider at startup, returns a simple prompt->response function.
        """
        # Auto-detect: try openai, then anthropic
        if provider == "auto":
            if OPENAI_AVAILABLE and os.environ.get("OPENAI_API_KEY"):
                provider = "openai"
            elif ANTHROPIC_AVAILABLE and os.environ.get("ANTHROPIC_API_KEY"):
                provider = "anthropic"
            else:
                provider = "none"

        if provider == "openai":
            return self._init_openai(model or self.DEFAULT_MODELS["openai"])
        elif provider == "anthropic":
            return self._init_anthropic(model or self.DEFAULT_MODELS["anthropic"])
        else:
            return lambda prompt: ""  # Empty = use fallback

    def _init_openai(self, model: str) -> Callable[[str], str]:
        """Initialize OpenAI client and return call function."""
        api_key = os.environ.get("OPENAI_API_KEY")
        if not api_key or not OPENAI_AVAILABLE:
            return lambda prompt: ""

        client = openai.OpenAI(api_key=api_key)

        def call(prompt: str) -> str:
            try:
                response = client.chat.completions.create(
                    model=model,
                    messages=[{"role": "user", "content": prompt}],
                    max_tokens=500,
                    temperature=0,
                )
                return response.choices[0].message.content.strip()
            except Exception:
                return ""

        return call

    def _init_anthropic(self, model: str) -> Callable[[str], str]:
        """Initialize Anthropic client and return call function."""
        api_key = os.environ.get("ANTHROPIC_API_KEY")
        if not api_key or not ANTHROPIC_AVAILABLE:
            return lambda prompt: ""

        client = anthropic.Anthropic(api_key=api_key)

        def call(prompt: str) -> str:
            try:
                response = client.messages.create(
                    model=model,
                    max_tokens=500,
                    temperature=0,
                    messages=[{"role": "user", "content": prompt}],
                )
                return response.content[0].text.strip()
            except Exception:
                return ""

        return call

    # === Registration API ===

    def register_server(
        self,
        name: str,
        command: list[str],
        args: Optional[dict] = None,
        tool_prefix: str = ""
    ) -> dict:
        """Register an MCP server for routing.

        Args:
            name: Unique server identifier
            command: Subprocess command to spawn server
            args: Optional initialization arguments
            tool_prefix: Prefix for tool names from this server

        Returns:
            Registration confirmation dict
        """
        with self._lock:
            config = ServerConfig(
                name=name,
                command=command,
                args=args or {},
                tool_prefix=tool_prefix
            )
            self._servers[name] = config

            return {
                "status": "registered",
                "name": name,
                "tool_prefix": tool_prefix,
                "registered_at": config.registered_at
            }

    def unregister_server(self, name: str) -> dict:
        """Remove a registered server.

        Args:
            name: Server identifier to remove

        Returns:
            Confirmation dict
        """
        with self._lock:
            existed = self._servers.pop(name, None) is not None
            # Kill connection if exists
            proc = self._connections.pop(name, None)
            if proc:
                proc.terminate()
            return {
                "status": "unregistered" if existed else "not_found",
                "name": name
            }

    def shutdown(self) -> None:
        """Shutdown all backend connections and socket listener."""
        # Stop socket listener first
        self.stop_socket_listener()

        with self._lock:
            for _, proc in list(self._connections.items()):
                try:
                    proc.terminate()
                    proc.wait(timeout=5)
                except Exception:
                    proc.kill()
            self._connections.clear()

    # ─────────────────────────────────────────────────────────────
    # Socket Listener for External Clients
    # ─────────────────────────────────────────────────────────────

    def start_socket_listener(self, port: int = 0, force_primary: bool = False) -> int:
        """Start socket listener with federation support.

        Checks for existing main router first. If one exists and is responsive,
        this router becomes secondary and proxies requests to the main.
        Otherwise, this router becomes primary.

        Args:
            port: Port to listen on (0 for auto-assign).
            force_primary: If True, always try to become primary (for testing).

        Returns:
            The actual port being used (main router's port if secondary).
        """
        # Federation check: is there already a main router?
        if not force_primary:
            main_port = self._check_main_router()
            if main_port:
                # Become secondary - proxy to main router
                self._is_primary = False
                self._main_router_port = main_port
                self._socket_port = main_port  # Report main's port
                _router_log("federation", f"Joined as secondary, main router on port {main_port}")
                return main_port

        # Try to become primary
        max_retries = 3
        for attempt in range(max_retries):
            try:
                self._socket_server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
                self._socket_server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
                self._socket_server.bind(("127.0.0.1", port))
                self._socket_server.listen(5)
                self._socket_port = self._socket_server.getsockname()[1]
                self._socket_running = True
                self._is_primary = True

                # Write port to file for client/secondary discovery
                self._port_file.parent.mkdir(parents=True, exist_ok=True)
                self._port_file.write_text(str(self._socket_port))

                # Start accept loop in background thread
                self._socket_thread = Thread(target=self._socket_accept_loop, daemon=True)
                self._socket_thread.start()

                _router_log("federation", f"Started as PRIMARY on port {self._socket_port}")
                return self._socket_port

            except OSError as e:
                # Port binding failed - likely race condition
                if e.errno == 98:  # EADDRINUSE
                    _router_log("federation", f"Bind failed (attempt {attempt + 1}), checking for main router")
                    if self._socket_server:
                        self._socket_server.close()
                        self._socket_server = None

                    # Another router might have just started - check again
                    import time
                    time.sleep(0.1 * (attempt + 1))  # Backoff
                    main_port = self._check_main_router()
                    if main_port:
                        self._is_primary = False
                        self._main_router_port = main_port
                        self._socket_port = main_port
                        _router_log("federation", f"Lost race, joined as secondary on port {main_port}")
                        return main_port
                else:
                    raise

        # All retries failed
        raise RuntimeError("Failed to start socket listener after retries")

    def stop_socket_listener(self) -> None:
        """Stop socket listener and clean up port file."""
        self._socket_running = False
        if self._socket_server:
            try:
                self._socket_server.close()
            except Exception:
                pass
        # Only delete port file if we're the primary (we created it)
        if self._is_primary and self._port_file.exists():
            try:
                self._port_file.unlink()
            except Exception:
                pass

