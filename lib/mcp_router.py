"""
MCP Router - Passthrough router with response summarization.

Routes MCP requests to registered target servers, returns responses
with {summary, full} envelope where summary is Haiku-generated.

Usage:
    from mcp_router import MCPRouter, RouterResponse

    router = MCPRouter()
    router.register_server("serena", ["python", "-m", "serena"], {"tool_prefix": "serena"})
    response = router.route("serena", "find_symbol", {"name": "MyClass"})
    print(response.summary)  # Haiku-generated summary
    print(response.full)     # Full response (access only if needed)
"""

