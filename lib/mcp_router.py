@dataclass
class RouterResponse:
    """Response envelope with summary and full response.

    The summary is generated by Haiku and should be sufficient for most cases.
    Access .full only when you need the complete response data.
    """
    summary: str
    full: Any
    correlation_id: str = ""

    def __repr__(self):
        return (
            f"RouterResponse(\n"
            f"  summary={self.summary!r},\n"
            f"  full=<available - access only if needed>,\n"
            f"  correlation_id={self.correlation_id!r}\n"
            f")"
        )

    def __str__(self):
        return (
            f"Summary: {self.summary}\n"
            f"[Full response available via .full - access only if needed]"
        )


@dataclass
class ServerConfig:
    """Configuration for a registered MCP server."""
    name: str
    command: list[str]
    args: dict = field(default_factory=dict)
    tool_prefix: str = ""
    registered_at: str = ""

    def __post_init__(self):
        if not self.registered_at:
            self.registered_at = datetime.now(timezone.utc).isoformat()


