    def _check_main_router(self) -> Optional[int]:
        """Check if a main router exists and is responsive.

        Returns:
            Port of main router if alive, None otherwise.
        """
        if not self._port_file.exists():
            return None

        try:
            port = int(self._port_file.read_text().strip())
            # Try to connect and ping
            sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            sock.settimeout(2.0)
            sock.connect(("127.0.0.1", port))

            # Send ping request
            request = {
                "jsonrpc": "2.0",
                "id": 1,
                "method": "tools/call",
                "params": {"name": "router__ping", "arguments": {}}
            }
            sock.sendall(json.dumps(request).encode() + b"\n")

            # Wait for response
            response_data = b""
            while b"\n" not in response_data:
                chunk = sock.recv(4096)
                if not chunk:
                    break
                response_data += chunk

            sock.close()

            if response_data:
                response = json.loads(response_data.decode().strip())
                if "result" in response:
                    _router_log("federation", f"Main router alive on port {port}")
                    return port
        except (socket.error, json.JSONDecodeError, ValueError) as e:
            _router_log("federation", f"Main router check failed: {e}", "DEBUG")
        except Exception as e:
            _router_log("federation", f"Unexpected error checking main router: {e}", "WARN")

        return None

    def _proxy_to_main(self, request: dict) -> dict:
        """Proxy a request to the main router.

        Args:
            request: JSON-RPC request to forward.

        Returns:
            Response from main router.
        """
        if not self._main_router_port:
            return {"error": {"code": -32603, "message": "No main router configured"}}

        try:
            sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            sock.settimeout(30.0)
            sock.connect(("127.0.0.1", self._main_router_port))

            # Send request
            sock.sendall(json.dumps(request).encode() + b"\n")

            # Receive response
            response_data = b""
            while b"\n" not in response_data:
                chunk = sock.recv(8192)
                if not chunk:
                    break
                response_data += chunk

            sock.close()

            if response_data:
                return json.loads(response_data.decode().strip())
            return {"error": {"code": -32603, "message": "Empty response from main router"}}

        except socket.timeout:
            _router_log("federation", "Proxy timeout to main router", "ERROR")
            return {"error": {"code": -32603, "message": "Timeout proxying to main router"}}
        except Exception as e:
            _router_log("federation", f"Proxy error: {e}", "ERROR")
            return {"error": {"code": -32603, "message": f"Proxy error: {e}"}}

    def is_primary(self) -> bool:
        """Check if this router is the primary (owns socket listener)."""
        return self._is_primary

    def _socket_accept_loop(self) -> None:
        """Accept connections and spawn handler threads."""
        self._active_socket_connections = 0
        self._total_socket_accepts = 0
        _router_log("socket", f"Accept loop started on port {self._socket_port}")

        while self._socket_running:
            try:
                self._socket_server.settimeout(1.0)  # Check running flag periodically
                try:
                    client, addr = self._socket_server.accept()
                    self._total_socket_accepts += 1
                    self._active_socket_connections += 1
                    conn_id = self._total_socket_accepts
                    _router_log("socket", f"ACCEPT conn_id={conn_id} from={addr} active={self._active_socket_connections}")

                    # Wrap handler to track connection lifecycle
                    def handle_and_track(c, cid):
                        try:
                            self._handle_socket_client(c, cid)
                        finally:
                            self._active_socket_connections -= 1
                            _router_log("socket", f"CLOSE conn_id={cid} active={self._active_socket_connections}")

                    Thread(
                        target=handle_and_track,
                        args=(client, conn_id),
                        daemon=True
                    ).start()
                except socket.timeout:
                    continue
            except Exception as e:
                if self._socket_running:
                    _router_log("socket", f"Accept error: {e}", "ERROR")
                    continue
                break
        _router_log("socket", "Accept loop stopped")

    def _handle_socket_client(self, client: socket.socket, conn_id: int = 0) -> None:
        """Handle a single client connection.

        Reads JSON-RPC request, routes it, sends response.
        Connection is closed after one request-response cycle.
        """
        import time
        start_time = time.time()
        tool_name = "unknown"
        log_prefix = f"conn_id={conn_id}"

        try:
            # Set timeout on socket operations
            client.settimeout(30.0)  # 30 second timeout for reads
            _router_log("socket", f"{log_prefix} Reading request...")

            # Read request (newline-delimited JSON)
            data = b""
            while b"\n" not in data:
                chunk = client.recv(4096)
                if not chunk:
                    _router_log("socket", f"{log_prefix} Client disconnected before sending data", "WARN")
                    return
                data += chunk

            read_time = time.time()
            _router_log("socket", f"{log_prefix} Received {len(data)} bytes in {int((read_time - start_time) * 1000)}ms")

            request = json.loads(data.decode().strip())
            request_id = request.get("id")
            method = request.get("method", "")
            params = request.get("params", {})
            _router_log("socket", f"{log_prefix} Parsed request: method={method} id={request_id}")

            # Route the request (same logic as stdio)
            if method == "tools/list":
                # Return all available tools from all backends
                tools = self._list_all_tools_for_socket()
                result = {"tools": tools}
                response = {
                    "jsonrpc": "2.0",
                    "id": request_id,
                    "result": result
                }
                response_bytes = json.dumps(response).encode() + b"\n"
                client.sendall(response_bytes)
                duration_ms = int((time.time() - start_time) * 1000)
                _router_log("socket", f"{log_prefix} COMPLETE tools/list duration={duration_ms}ms tools_count={len(tools)}")
                return

            elif method == "tools/call":
                tool_name = params.get("name", "")
                args = params.get("arguments", {})
                _router_log("socket", f"{log_prefix} ROUTE tool={tool_name} args_keys={list(args.keys())}")

                # Handle router built-in tools first
                if tool_name == "router__ping":
                    result = {"content": [{"type": "text", "text": "pong! Router is working."}]}
                elif tool_name == "router__telemetry":
                    if self.telemetry:
                        summary = self.telemetry.get_summary()
                        summary["socket_stats"] = self.get_socket_stats()
                        summary["federation"] = {"is_primary": self._is_primary, "main_port": self._main_router_port}
                        result = {"content": [{"type": "text", "text": json.dumps(summary, indent=2)}]}
                    else:
                        result = {"content": [{"type": "text", "text": "Telemetry not enabled"}]}
                elif tool_name == "router__list_tools":
                    tools = self._list_all_tools_for_socket()
                    result = {"content": [{"type": "text", "text": json.dumps({"tools": [t["name"] for t in tools]}, indent=2)}]}
                elif "__" in tool_name:
                    prefix, actual_tool = tool_name.split("__", 1)
                    # Find backend by prefix
                    destination = None
                    for server in self.list_servers():
                        if server.get("tool_prefix") == prefix or server["name"] == prefix:
                            destination = server["name"]
                            break

                    if not destination:
                        _router_log("socket", f"{log_prefix} Unknown backend prefix: {prefix}", "ERROR")
                        result = {"content": [{"type": "text", "text": f"Error: Unknown backend prefix: {prefix}"}], "isError": True}
                    else:
                        _router_log("socket", f"{log_prefix} Routing to backend={destination} tool={actual_tool}")
                        _route_start = time.time()  # noqa: F841 - kept for future duration logging
                        response = self.route(destination, actual_tool, args)
                        route_duration = int((time.time() - _route_start) * 1000)
                        _router_log("socket", f"{log_prefix} Backend responded in {route_duration}ms")

                        backend_result = response.full
                        if isinstance(backend_result, dict) and "error" in backend_result:
                            _router_log("socket", f"{log_prefix} Backend error: {str(backend_result.get('error', ''))[:100]}", "ERROR")
                            result = {"content": [{"type": "text", "text": f"Error: {backend_result['error']}"}], "isError": True}
                        else:
                            if isinstance(backend_result, dict) and "result" in backend_result:
                                full_content = backend_result["result"]
                            else:
                                full_content = backend_result
                            result = full_content
                            result_size = len(json.dumps(result)) if result else 0
                            _router_log("socket", f"{log_prefix} Success result_size={result_size}")
                else:
                    _router_log("socket", f"{log_prefix} Tool name not prefixed: {tool_name}", "ERROR")
                    result = {"content": [{"type": "text", "text": "Tool name must be prefixed: prefix__tool"}], "isError": True}
            else:
                _router_log("socket", f"{log_prefix} Unsupported method: {method}", "WARN")
                result = {"error": f"Unsupported method: {method}"}

            # Send response
            response = {
                "jsonrpc": "2.0",
                "id": request_id,
                "result": result
            }
            response_bytes = json.dumps(response).encode() + b"\n"
            client.sendall(response_bytes)

            # Track successful socket request in telemetry
            duration_ms = int((time.time() - start_time) * 1000)
            _router_log("socket", f"{log_prefix} COMPLETE tool={tool_name} duration={duration_ms}ms response_size={len(response_bytes)}")
            if self.telemetry:
                self._track_socket_event("success", tool_name, duration_ms)

        except socket.timeout:
            duration_ms = int((time.time() - start_time) * 1000)
            _router_log("socket", f"{log_prefix} TIMEOUT tool={tool_name} duration={duration_ms}ms", "ERROR")
            if self.telemetry:
                self._track_socket_event("timeout", tool_name, duration_ms)
            try:
                error_response = {
                    "jsonrpc": "2.0",
                    "id": None,
                    "error": {"code": -32603, "message": "Socket timeout"}
                }
                client.sendall(json.dumps(error_response).encode() + b"\n")
            except Exception:
                pass
        except Exception as e:
            duration_ms = int((time.time() - start_time) * 1000)
            _router_log("socket", f"{log_prefix} ERROR tool={tool_name} duration={duration_ms}ms error={str(e)[:100]}", "ERROR")
            if self.telemetry:
                self._track_socket_event("error", tool_name, duration_ms, str(e)[:100])
            try:
                error_response = {
                    "jsonrpc": "2.0",
                    "id": None,
                    "error": {"code": -32603, "message": str(e)}
                }
                client.sendall(json.dumps(error_response).encode() + b"\n")
            except Exception:
                pass
        finally:
            try:
                client.close()
            except Exception:
                pass

    def _track_socket_event(
        self,
        status: str,
        tool_name: str,
        duration_ms: int,
        error_msg: str = ""
    ) -> None:
        """Track socket connection event in telemetry.
        
        Args:
            status: "success", "timeout", or "error"
            tool_name: Tool that was called
            duration_ms: Request duration in milliseconds
            error_msg: Error message if any
        """
        if not self.telemetry:
            return
            
        # Add to telemetry data under socket_events
        with self.telemetry._lock:
            if not hasattr(self.telemetry, '_socket_events'):
                self.telemetry._socket_events = []
            
            event = {
                "ts": datetime.now(timezone.utc).isoformat(),
                "status": status,
                "tool": tool_name,
                "duration_ms": duration_ms,
                "error_msg": error_msg
            }
            self.telemetry._socket_events.append(event)
            
            # Keep last 100 events
            if len(self.telemetry._socket_events) > 100:
                self.telemetry._socket_events = self.telemetry._socket_events[-100:]

    def store_content(self, content: Any) -> str:
        """Store content and return a unique content_id."""
        self._content_id_counter += 1
        content_id = f"content_{self._content_id_counter}"
        self._content_store[content_id] = content
        return content_id

    def get_full_content(self, content_id: str) -> dict:
        """Retrieve stored content by ID. Returns error dict if not found."""
        if content_id in self._content_store:
            content = self._content_store.pop(content_id)  # Remove after retrieval (one-time use)
            return {"content": content}
        return {"error": f"Content not found for ID: {content_id}"}

    def get_socket_stats(self) -> dict:
        """Get current socket connection statistics.
        
        Returns:
            Dict with active connections, total accepts, and event summary
        """
        active = getattr(self, '_active_socket_connections', 0)
        total = getattr(self, '_total_socket_accepts', 0)
        
        socket_events = []
        if self.telemetry:
            socket_events = getattr(self.telemetry, '_socket_events', [])
        
        # Count by status
        by_status = {}
        for evt in socket_events:
            status = evt.get("status", "unknown")
            by_status[status] = by_status.get(status, 0) + 1
        
        return {
            "active_connections": active,
            "total_accepts": total,
            "events_tracked": len(socket_events),
            "by_status": by_status,
            "recent_events": socket_events[-10:] if socket_events else []
        }

