def start_stdio_server(router: MCPRouter):
    """Run stdio-based MCP server loop.

    Reads JSON-RPC requests from stdin, routes through router,
    writes responses to stdout.

    Implements MCP protocol:
    - initialize/initialized handshake
    - tools/list (aggregates from all backends, prefixes tool names)
    - tools/call (routes based on prefix)
    """
    def send(msg: dict) -> None:
        print(json.dumps(msg), flush=True)

    def list_all_tools() -> list[dict]:
        """Get tools from all backends, prefix names with backend."""
        # Router's own tools
        all_tools = [
            {
                "name": "router__ping",
                "description": "Test tool that returns a simple message",
                "inputSchema": {"type": "object", "properties": {}},
            },
            {
                "name": "router__telemetry",
                "description": "Get real-time telemetry data (tool usage, tokens, errors, timing)",
                "inputSchema": {"type": "object", "properties": {}},
            },
            {
                "name": "router__telemetry_analysis",
                "description": "Get analysis of token usage trends and optimization effectiveness",
                "inputSchema": {"type": "object", "properties": {}},
            },
        ]
        for server in router.list_servers():
            name = server["name"]
            prefix = server.get("tool_prefix") or name

            # Get tools from this backend
            try:
                response = router._forward_to_server(
                    router._servers[name],
                    "__list__",  # Special: triggers tools/list
                    {}
                )
                if "result" in response and "tools" in response["result"]:
                    for tool in response["result"]["tools"]:
                        # Prefix tool name
                        tool["name"] = f"{prefix}__{tool['name']}"
                        all_tools.append(tool)
            except Exception:
                pass  # Skip failed backends
        return all_tools

    for line in sys.stdin:
        request_id = None
        try:
            request = json.loads(line.strip())
            method = request.get("method", "")
            params = request.get("params", {})
            request_id = request.get("id")

            # MCP handshake
            if method == "initialize":
                result = {
                    "protocolVersion": "2024-11-05",
                    "capabilities": {"tools": {}},
                    "serverInfo": {
                        "name": "mcp-router",
                        "version": "1.0.0"
                    }
                }
            elif method == "notifications/initialized":
                continue  # Notification, no response

            # Tool discovery
            elif method == "tools/list":
                result = {"tools": list_all_tools()}

            # Tool execution - parse prefix to route
            elif method == "tools/call":
                tool_name = params.get("name", "")
                args = params.get("arguments", {})

                # Handle router's own tools first
                if tool_name == "router__ping":
                    result = {"content": [{"type": "text", "text": "pong! Router is working."}]}

                elif tool_name == "router__telemetry":
                    if router.telemetry:
                        summary = router.telemetry.get_summary()
                        result = {"content": [{"type": "text", "text": json.dumps(summary, indent=2)}]}
                    else:
                        result = {"content": [{"type": "text", "text": "Telemetry not enabled"}]}

                elif tool_name == "router__telemetry_analysis":
                    if router.telemetry:
                        analysis = analyze_telemetry_trends(router.telemetry)
                        result = {"content": [{"type": "text", "text": json.dumps(analysis, indent=2)}]}
                    else:
                        result = {"content": [{"type": "text", "text": "Telemetry not enabled"}]}

                # Parse prefix__toolname for backend routing
                elif "__" in tool_name:
                    prefix, actual_tool = tool_name.split("__", 1)
                    # Find backend by prefix
                    destination = None
                    for server in router.list_servers():
                        if server.get("tool_prefix") == prefix or server["name"] == prefix:
                            destination = server["name"]
                            break
                    if not destination:
                        result = {"content": [{"type": "text", "text": f"Error: Unknown backend prefix: {prefix}"}], "isError": True}
                    else:
                        response = router.route(destination, actual_tool, args)
                        # Return {summary, full} envelope so Claude can read summary first
                        backend_result = response.full
                        if isinstance(backend_result, dict) and "error" in backend_result:
                            result = {"content": [{"type": "text", "text": f"Error: {backend_result['error']}"}], "isError": True}
                        else:
                            # Extract actual content from backend response
                            if isinstance(backend_result, dict) and "result" in backend_result:
                                full_content = backend_result["result"]
                            else:
                                full_content = backend_result

                            # Return structured envelope with summary and full
                            envelope = {
                                "summary": response.summary,
                                "full": full_content
                            }
                            result = {"content": [{"type": "text", "text": json.dumps(envelope)}]}
                else:
                    result = {"content": [{"type": "text", "text": "Tool name must be prefixed: prefix__tool"}], "isError": True}

            # Router management API
            elif method == "router_register":
                result = router.register_server(**params)
            elif method == "router_list":
                result = router.list_servers()
            elif method == "router_unregister":
                result = router.unregister_server(**params)

            else:
                result = {"error": f"Unknown method: {method}"}

            # Write response (skip for notifications)
            if request_id is not None:
                send({
                    "jsonrpc": "2.0",
                    "id": request_id,
                    "result": result
                })

        except json.JSONDecodeError as e:
            send({
                "jsonrpc": "2.0",
                "id": request_id,
                "error": {"code": -32700, "message": f"Parse error: {e}"}
            })
        except Exception as e:
            send({
                "jsonrpc": "2.0",
                "id": request_id,
                "error": {"code": -32603, "message": str(e)}
            })


if __name__ == "__main__":
    router = MCPRouter()

    # Auto-register default server from env if specified
    default_server = os.environ.get("MCP_ROUTER_DEFAULT_SERVER")
    if default_server:
        router.register_server("default", default_server.split(), {})

    # Start socket listener for external clients (hooks, CLIs)
    port = router.start_socket_listener()
    sys.stderr.write(f"Router socket listener started on port {port}\n")

    try:
        start_stdio_server(router)
    finally:
        router.shutdown()
